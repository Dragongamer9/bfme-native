#!/usr/bin/env python3
"""Write docs/SCOPE.md: what Edain + submod need from the engine, and what already exists.

Usage: report.py data/rotwk docs/SCOPE.md
"""
import json
import os
import sys


def main():
    d, out = sys.argv[1], sys.argv[2]
    usage = json.load(open(os.path.join(d, "ini_usage.json")))
    mods = json.load(open(os.path.join(d, "modules.json")))["modules"]
    tables = json.load(open(os.path.join(d, "tables.json")))
    exe_mods = {m["name"]: m for m in mods}

    rows = [m for m in usage["modules"] if m["in_rotwk_exe"]]
    tot = sum(m["uses"] for m in rows) or 1
    have = [m for m in rows if m["in_generals"]]
    need = [m for m in rows if not m["in_generals"]]
    unused = [m for m in mods if m["name"] not in {r["module"] for r in rows}]

    L = []
    L.append("# Port scope: RotWK + Edain\n")
    L.append("Generated by `tools/report.py` from the RotWK `game.dat` scan and the mod's INI data.\n")
    L.append("## Summary\n")
    L.append(f"- Engine module classes in RotWK: **{len(mods)}** "
             f"({sum(1 for m in mods if m['in_generals'])} also in Generals, "
             f"{sum(1 for m in mods if not m['in_generals'])} BFME-only)")
    L.append(f"- Module classes the mod data uses: **{len(rows)}**. Of those, {len(have)} already exist in "
             f"the Generals code ({100 * sum(m['uses'] for m in have) / tot:.0f}% of all module instances) "
             f"and **{len(need)} must be written**")
    L.append(f"- RotWK module classes the mod never uses: {len(unused)} (can wait)")
    L.append(f"- INI files: {usage['ini_files']}; top-level block types: {len(usage['blocks'])}")
    ft = tables["field_tables"]
    L.append(f"- INI parse tables found in the exe: {len(ft)}, {sum(1 for t in ft if 'match' in t)} matched "
             f"to Generals classes; BFME-added fields in matched tables: "
             f"{sum(len(t.get('new_in_bfme', [])) for t in ft)}\n")

    L.append("## Modules to write, by how often the mod uses them\n")
    L.append("| # | Module | Uses | Distinct fields set | Factory in game.dat |")
    L.append("|---|---|---:|---:|---|")
    for i, m in enumerate(need, 1):
        em = exe_mods.get(m["module"], {})
        L.append(f"| {i} | `{m['module']}` | {m['uses']} | {len(m['fields'])} | "
                 f"`{em.get('newModuleInstance', 0):08X}` |")
    L.append("\n## Modules already in the Generals code (need BFME field extensions checked)\n")
    L.append("| Module | Uses | Fields set |")
    L.append("|---|---:|---:|")
    for m in have:
        L.append(f"| `{m['module']}` | {m['uses']} | {len(m['fields'])} |")
    L.append("\n## Top-level INI blocks\n")
    L.append("| Block | Count |")
    L.append("|---|---:|")
    for k, v in list(usage["blocks"].items())[:60]:
        L.append(f"| `{k}` | {v} |")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out}: {len(need)} modules to write, {len(have)} existing", file=sys.stderr)


if __name__ == "__main__":
    main()
